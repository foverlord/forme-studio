/**
 * Copy booking delivery strings from the art CSV into content/booking-delivery.ts.
 * Does not author Russian or Kazakh sentences.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const candidates = [
  join(root, "uploads/booking-strings.csv"),
  "/home/ubuntu/.cursor/projects/workspace/uploads/strings_2b01.csv",
];
const csvPath = candidates.find((path) => existsSync(path));
if (!csvPath) throw new Error(`CSV not found:\n${candidates.join("\n")}`);

function parseCsv(csv) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < csv.length; i += 1) {
    const char = csv[i];
    if (quoted) {
      if (char === '"') {
        if (csv[i + 1] === '"') {
          field += '"';
          i += 1;
        } else quoted = false;
      } else field += char;
    } else if (char === '"') quoted = true;
    else if (char === ",") {
      row.push(field);
      field = "";
    } else if (char === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (char !== "\r") field += char;
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const keys = [
  "booking.sending",
  "booking.success.title",
  "booking.success.text",
  "booking.error.title",
  "booking.error.text",
  "booking.error.whatsapp",
  "booking.error.retry",
  "booking.error.rateLimit",
  "booking.whatsapp.template",
];

const table = parseCsv(readFileSync(csvPath, "utf8"));
const map = new Map();
for (const cells of table.slice(1)) {
  const key = cells[0];
  if (!keys.includes(key)) continue;
  map.set(key, { ru: cells[1] ?? "", kk: cells[2] ?? "" });
}
const missing = keys.filter((key) => !map.get(key)?.ru || !map.get(key)?.kk);
if (missing.length) {
  console.error(missing.join("\n"));
  throw new Error(`missing booking keys: ${missing.length}`);
}

function pack(lang) {
  return {
    sending: map.get("booking.sending")[lang],
    delivered: {
      title: map.get("booking.success.title")[lang],
      text: map.get("booking.success.text")[lang],
    },
    sendError: {
      title: map.get("booking.error.title")[lang],
      text: map.get("booking.error.text")[lang],
      whatsapp: map.get("booking.error.whatsapp")[lang],
      retry: map.get("booking.error.retry")[lang],
      rateLimit: map.get("booking.error.rateLimit")[lang],
    },
    whatsappTemplate: map.get("booking.whatsapp.template")[lang],
  };
}

const body = `/** Generated by scripts/apply-booking-strings.mjs from the art CSV. Do not edit strings here. */
export const bookingDelivery = ${JSON.stringify({ ru: pack("ru"), kk: pack("kk") }, null, 2)} as const;
`;

writeFileSync(join(root, "content/booking-delivery.ts"), body);
console.log(`wrote booking-delivery.ts from ${csvPath}`);
